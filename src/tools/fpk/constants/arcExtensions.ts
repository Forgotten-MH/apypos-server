/** hash → extension (for extraction) */
export const EXT_BY_HASH = new Map<number, string>();

/** extension → hash (for repacking). Only stores first hash for each extension. */
export const HASH_BY_EXT = new Map<string, number>();

for (const [typeName, ext] of TYPE_EXT_PAIRS) {
  const hash = jamcrc(typeName);
  EXT_BY_HASH.set(hash, ext);
  if (!HASH_BY_EXT.has(ext)) {
    HASH_BY_EXT.set(ext, hash);
  }
}

/** Get file extension for a hash, or fall back to `.{hex}` */
export function getExtension(hash: number): string {
  return EXT_BY_HASH.get(hash) ?? `.${hash.toString(16)}`;
}

/** Get hash for a file extension */
export function getHash(ext: string): number | undefined {
  return HASH_BY_EXT.get(ext);
}
