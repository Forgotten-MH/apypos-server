import crcjam from 'crc/crcjam';

/**
 * JAMCRC: CRC-32/JAMCRC — the bitwise complement of standard CRC-32,
 * masked to 31 bits. Matches the Python reference:
 * `(zlib.crc32(s.encode()) ^ 0xFFFFFFFF) & 0x7FFFFFFF`
 */
export function jamcrc(str: string): number {
  // crc/crcjam returns CRC-32/JAMCRC (inverted CRC-32)
  // We mask to 31 bits to match the game's convention
  return crcjam(Buffer.from(str)) & 0x7fffffff;
}

